export const textWidth = (s, px) => s.length * 6 * px - px;
export function drawText(ctx, str, x, y, { px = 3, color = '#fff', align = 'left' } = {}) {
  const s = String(str).toUpperCase(), w = textWidth(s, px);
  let X = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const Y = Math.round(y);
  ctx.fillStyle = color;
  for (const ch of s) {
    (G[ch] ?? G[' ']).split('|').forEach((row, r) => [...row].forEach((c, k) => { if (c === '#') ctx.fillRect(X + k * px, Y + r * px, px, px); }));
    X += 6 * px;
  }
  return w;
}
